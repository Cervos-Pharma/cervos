let src = fs.readFileSync(FILE, 'utf8');

// 1. Add alerts.fromPharmacy to the sw block (missing there too).
const swAnchor = "    'alerts.subscriptionStatus': 'Hali ya Usajili wa Tawi',";
if (src.includes(swAnchor) && !src.includes("'alerts.fromPharmacy': 'Kutoka kwa duka la dawa lako'")) {
  src = src.replace(swAnchor, swAnchor + "\n    'alerts.fromPharmacy': 'Kutoka kwa duka la dawa lako',");
}

// 2. Build grouped entries and splice into the en block right after "en: {".
const groups = {};
for (const [k, v] of Object.entries(EN)) {
  const prefix = k.split('.')[0];
  (groups[prefix] ||= []).push([k, v]);
}
let inject = '';
for (const [prefix, entries] of Object.entries(groups)) {
  inject += `\n    // ${prefix[0].toUpperCase() + prefix.slice(1)} (full coverage)\n`;
  for (const [k, v] of entries) {
    inject += `    '${k}': ${JSON.stringify(v)},\n`;
  }
}
const enMarker = src.indexOf('  en: {');
const insertAt = src.indexOf('\n', enMarker) + 1;
src = src.slice(0, insertAt) + inject + src.slice(insertAt);

fs.writeFileSync(FILE, src);
console.log('Injected', Object.keys(EN).length, 'English keys + alerts.fromPharmacy (sw).');
